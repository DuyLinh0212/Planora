import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const [application] = process.argv.slice(2);
const projects = {
  user: 'frontend/Planora.Web.User',
  admin: 'frontend/Planora.Web.Admin',
};

if (!projects[application]) {
  throw new Error('Usage: node tools/ci/write-frontend-environment.mjs <user|admin>');
}

const apiUrl = requiredEnvironmentVariable('PLANORA_API_URL').replace(/\/$/, '');
const parsedApiUrl = new URL(apiUrl);
if (parsedApiUrl.protocol !== 'https:' && parsedApiUrl.hostname !== 'localhost') {
  throw new Error('PLANORA_API_URL must use HTTPS outside localhost.');
}

const values = {
  production: true,
  apiUrl,
};

if (application === 'user') {
  const googleClientId = requiredEnvironmentVariable('PLANORA_GOOGLE_CLIENT_ID');
  values.googleClientId = googleClientId;
  values.gmailOAuthClientId = googleClientId;
}

const lines = Object.entries(values).map(
  ([key, value]) => `  ${key}: ${typeof value === 'string' ? JSON.stringify(value) : value},`,
);
const content = `// Generated by tools/ci/write-frontend-environment.mjs.\nexport const environment = {\n${lines.join('\n')}\n};\n`;
const destination = path.resolve(projects[application], 'src/environments/environment.ts');

await mkdir(path.dirname(destination), { recursive: true });
await writeFile(destination, content, 'utf8');
console.log(`Generated production environment for ${application}.`);

function requiredEnvironmentVariable(name) {
  const value = process.env[name]?.trim();
  if (!value) {
    throw new Error(`${name} is required.`);
  }
  return value;
}
